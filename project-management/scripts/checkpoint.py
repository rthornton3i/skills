#!/usr/bin/env python3
"""Session-continuity helper: snapshot live project state and verify restart dependencies.

  checkpoint.py [--project DIR] snapshot [--write-memory]   print live state; optionally refresh the
                                                            auto block in memory/project_state.md
  checkpoint.py [--project DIR] restart-check               verify everything in <agent folder>/project-manifest.json
  checkpoint.py [--project DIR] memory-status               list memory files, their age, index consistency
  checkpoint.py [--project DIR] brief                       start-up summary (under 25 lines): branch, next step
  checkpoint.py [--project DIR] lookup KEYWORD...           search <agent folder>/state/ (Markdown and JSONL), print the matching entries

Memory normally lives outside the repo, in the tool's per-project folder (~/.agent/projects/<slug>/memory/, or ~/.claude/projects/... when that exists);
override with --memory-dir or the AGENT_MEMORY_DIR environment variable. Nothing here ever prints a secret value;
environment keys are reported as present/absent with a length only.
"""
import argparse, datetime as dt, filecmp, json, os, re, shutil, subprocess, sys
from pathlib import Path

BEGIN, END = "<!-- auto:begin -->", "<!-- auto:end -->"
STATE_TEMPLATE = """---
name: project-state
description: RESUME HERE - current work, work in flight, next step and open loose ends for this project
metadata:
  type: project
---

{begin}
{end}

## In flight
(What is being worked on right now, in one or two lines.)

## Next step
(The single next action a fresh session should take.)

## Where details live
(Point to <agent folder>/state/INDEX.md and the lookup command. Keep this whole note at most 2,600 bytes.)
"""


def agent_dir(project):
    """The project's agent folder: .agent if it exists, else .claude (Claude Code projects)."""
    project = Path(project)
    return project / ".agent" if (project / ".agent").is_dir() else project / ".claude"


def slugify(p):
    return re.sub(r"[^A-Za-z0-9]", "-", str(p))


def run(cmd, cwd=None):
    try:
        r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=30)
        return r.returncode, (r.stdout or "").rstrip()  # rstrip only: git status output starts with a significant space
    except (OSError, subprocess.SubprocessError):
        return 1, ""


def memory_root(project, override=None):
    """Memory folder: --memory-dir / AGENT_MEMORY_DIR, else ~/.claude/projects/<slug>/memory if its parent exists, else ~/.agent/projects/<slug>/memory."""
    if override:
        return Path(os.path.expanduser(override))
    env = os.environ.get("AGENT_MEMORY_DIR")
    if env:
        return Path(os.path.expanduser(env))
    claude = Path.home() / ".claude" / "projects" / slugify(project) / "memory"
    if claude.parent.is_dir() or (Path.home() / ".claude").is_dir():
        return claude
    return Path.home() / ".agent" / "projects" / slugify(project) / "memory"


def paths(project, override=None):
    """Returns (project, memory dir in effect)."""
    project = Path(project).resolve()
    return project, memory_root(project, override)


def age(p):
    if not p.exists():
        return None
    return dt.datetime.now().timestamp() - p.stat().st_mtime


def fmt_age(sec):
    if sec is None:
        return "missing"
    m = int(sec // 60)
    return f"{m} min ago" if m < 120 else f"{m // 60} h ago" if m < 2880 else f"{m // 1440} d ago"


def read_jsonl(p):
    out = []
    if p.exists():
        for line in p.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line:
                try:
                    out.append(json.loads(line))
                except json.JSONDecodeError:
                    pass
    return out


def find_gh():
    return shutil.which("gh") or next((str(Path(x) / "GitHub CLI" / "gh.exe") for x in
                                       (os.environ.get("ProgramFiles", r"C:\Program Files"),) if (Path(x) / "GitHub CLI" / "gh.exe").exists()), None)


# ---------------------------------------------------------------- snapshot
def snapshot(project, mem):
    lines = [f"_Auto snapshot {dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}, regenerated by checkpoint.py. Do not edit by hand._", ""]
    rc, branch = run(["git", "rev-parse", "--abbrev-ref", "HEAD"], project)
    if rc != 0:
        lines.append("- Git: not a repository")
    else:
        rc, up = run(["git", "rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}"], project)
        rel = ""
        rc2, cnt = run(["git", "rev-list", "--left-right", "--count", f"dev...{branch}"], project)
        if rc2 == 0 and cnt:
            behind, ahead = cnt.split()
            rel = f"; {ahead} ahead of / {behind} behind `dev`"
        lines.append(f"- Branch: `{branch}`{rel}; upstream: {'`' + up + '`' if rc == 0 else 'none (not pushed)'}")
        _, st = run(["git", "status", "--porcelain"], project)
        changed = [l for l in st.splitlines() if l.strip()]
        lines.append("- Working tree: clean" if not changed else f"- Working tree: {len(changed)} uncommitted change(s): " + ", ".join(f"`{l[3:]}`" for l in changed[:8]) + (" …" if len(changed) > 8 else ""))
        _, log = run(["git", "log", "-5", "--format=%h %s"], project)
        lines.append("- Recent commits: " + "; ".join(f"`{x}`" for x in log.splitlines()))
    mf = agent_dir(project) / "project-manifest.json"
    if mf.exists():
        lines.append(f"- Manifest: `{agent_dir(project).name}/project-manifest.json` (run `restart-check` to verify it)")
    else:
        lines.append(f"- No `{agent_dir(project).name}/project-manifest.json` yet (see the project-management skill)")
    state = mem / "project_state.md"
    lines.append(f"- Memory `project_state.md`: {fmt_age(age(state))}")
    return "\n".join(lines)


def write_memory(mem, text):
    mem.mkdir(parents=True, exist_ok=True)
    p = mem / "project_state.md"
    block = f"{BEGIN}\n{text}\n{END}"
    if not p.exists():
        p.write_text(STATE_TEMPLATE.format(begin=BEGIN, end=END).replace(f"{BEGIN}\n{END}", block), encoding="utf-8")
    else:
        s = p.read_text(encoding="utf-8")
        if BEGIN in s and END in s:
            s = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, s, flags=re.S)
        else:  # no markers yet: insert after front matter
            m = re.match(r"---\n.*?\n---\n", s, re.S)
            i = m.end() if m else 0
            s = s[:i] + "\n" + block + "\n" + s[i:]
        p.write_text(s, encoding="utf-8")
    return p


# ---------------------------------------------------------------- restart-check
class Report:
    def __init__(self):
        self.rows, self.fail = [], False

    def add(self, level, label, detail="", critical=True):
        self.rows.append((level, label, detail))
        if level == "MISSING" and critical:
            self.fail = True

    def show(self):
        for lv, lb, dt_ in self.rows:
            print(f"{lv:8} {lb}" + (f"  - {dt_}" if dt_ else ""))
        c = {k: sum(1 for r in self.rows if r[0] == k) for k in ("OK", "WARN", "MISSING")}
        print(f"\n{c['OK']} ok, {c['WARN']} warnings, {c['MISSING']} missing")


def parse_env(p):
    out = {}
    if p.exists():
        for line in p.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                out[k.strip()] = v.strip()
    return out


def restart_check(project, mem):
    rep = Report()
    mf = agent_dir(project) / "project-manifest.json"
    if not mf.exists():
        print(f"No {agent_dir(project).name}/project-manifest.json. Create one (see references/templates.md in the project-management skill).")
        return 2
    m = json.loads(mf.read_text(encoding="utf-8"))
    home_skills = Path.home() / (".claude" if (Path.home() / ".claude").is_dir() else ".agent") / "skills"
    for n in m.get("skills", {}).get("global", []):
        rep.add("OK" if (home_skills / n / "SKILL.md").exists() else "MISSING", f"global skill: {n}")
    for n in m.get("skills", {}).get("project", []):
        ok = (agent_dir(project) / "skills" / n / "SKILL.md").exists()
        rep.add("OK" if ok else "WARN", f"project skill: {n}", "" if ok else "not on this branch (project skills live in the repo)", critical=False)
    env = m.get("environment", {})
    if env.get("venv"):
        v = project / env["venv"]
        py = v / "Scripts" / "python.exe"
        py = py if py.exists() else v / "bin" / "python"
        rep.add("OK" if py.exists() else "MISSING", "virtual environment", f"{env['venv']}" + ("" if py.exists() else f"; create with {env.get('setup', 'the setup script')}"))
    if env.get("env_file"):
        vals = parse_env(project / env["env_file"])
        rep.add("OK" if (project / env["env_file"]).exists() else "MISSING", f"env file {env['env_file']}", "", critical=False)
        for k in env.get("env_keys", []):
            rep.add("OK" if vals.get(k) else "WARN", f"env key {k}", f"set ({len(vals[k])} chars)" if vals.get(k) else "empty or absent", critical=False)
    for t in m.get("tools", []):
        rep.add("OK" if shutil.which(t) or (t == "gh" and find_gh()) else "MISSING", f"tool: {t}")
    if "gh" in m.get("tools", []) and find_gh():
        rc, _ = run([find_gh(), "auth", "status"])
        rep.add("OK" if rc == 0 else "WARN", "gh authenticated", "" if rc == 0 else "run `gh auth login` before opening PRs", critical=False)
    rc, branch = run(["git", "rev-parse", "--abbrev-ref", "HEAD"], project)
    exp = m.get("branches", {}).get("current")
    if rc == 0:
        rep.add("OK" if not exp or branch == exp else "WARN", "git branch", f"on `{branch}`" + ("" if not exp or branch == exp else f"; manifest expects `{exp}`"), critical=False)
    rep.add("OK", "memory location", str(mem))
    idx = mem / "MEMORY.md"
    rep.add("OK" if idx.exists() else "WARN", "memory index", str(mem), critical=False)
    st = mem / "project_state.md"
    a = age(st)
    rep.add("OK" if a is not None else "WARN", "memory project_state.md", fmt_age(a), critical=False)
    if a is not None:
        rc, ts = run(["git", "log", "-1", "--format=%ct"], project)
        if rc == 0 and ts and float(ts) > st.stat().st_mtime + 60:
            rep.add("WARN", "memory older than last commit", "refresh with `checkpoint.py snapshot --write-memory` and update the narrative", critical=False)
    rep.show()
    return 1 if rep.fail else 0


# ---------------------------------------------------------------- memory-status
def memory_status(project, mem):
    if not mem.exists():
        print(f"No memory folder at {mem}")
        return 1
    files = sorted(p for p in mem.glob("*.md") if p.name != "MEMORY.md")
    idx = (mem / "MEMORY.md").read_text(encoding="utf-8") if (mem / "MEMORY.md").exists() else ""
    print(f"memory: {mem}")
    bad = 0
    for p in files:
        txt = p.read_text(encoding="utf-8")
        has_fm = txt.startswith("---") and "name:" in txt.split("---")[1] if txt.count("---") >= 2 else False
        indexed = p.name in idx
        flag = "" if (has_fm and indexed) else "  <- " + ("no front matter " if not has_fm else "") + ("not in MEMORY.md" if not indexed else "")
        bad += bool(flag)
        print(f"  {p.name:42} {fmt_age(age(p)):>12}{flag}")
    for name in re.findall(r"\(([^)]+\.md)\)", idx):
        if not (mem / name).exists():
            print(f"  MEMORY.md points to missing file: {name}")
            bad += 1
    long_lines = [l for l in idx.splitlines() if len(l) > 200]
    if long_lines:
        print(f"  {len(long_lines)} index line(s) longer than 200 characters")
    return 1 if bad else 0


# ---------------------------------------------------------------- brief and lookup
def run_utf8(cmd, cwd=None):
    """Like run(), but decodes UTF-8 with replacement, so a curly quote in a commit subject cannot crash."""
    try:
        r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=30)
        return r.returncode, (r.stdout or "").rstrip()
    except (OSError, subprocess.SubprocessError):
        return 1, ""


def compact_block(project, header=True):
    """Short live state (about 350 B): branch with ahead/behind and tree state, last commit.
    Written into the resume note by `snapshot --write-memory` and printed by `brief`."""
    out = [f"_Auto {dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%d %H:%M')} UTC by checkpoint.py; do not edit._"] if header else []
    rc, branch = run_utf8(["git", "rev-parse", "--abbrev-ref", "HEAD"], project)
    if rc != 0:
        out.append("- Git: not a repository, or no commits yet")
    else:
        rel = ""
        rc2, cnt = run_utf8(["git", "rev-list", "--left-right", "--count", f"dev...{branch}"], project)
        if rc2 == 0 and cnt:
            behind, ahead = cnt.split()
            rel = f"; {ahead} ahead of / {behind} behind `dev`"
        _, st = run_utf8(["git", "status", "--porcelain"], project)
        n = len([l for l in st.splitlines() if l.strip()])
        out.append(f"- Branch: `{branch}`{rel}; " + ("tree clean" if not n else f"{n} uncommitted change(s)"))
        rc3, last = run_utf8(["git", "log", "-1", "--format=%h %s"], project)
        if rc3 == 0 and last:
            h, _, subj = last.partition(" ")
            out.append(f"- Last commit: `{h} {subj if len(subj) <= 70 else subj[:67] + '...'}`")
    return "\n".join(out)


def resume_section(mem, heading="Next step"):
    """Text under `## <heading>` in the resume note (up to the next `## `), or None."""
    p = mem / "project_state.md"
    if not p.exists():
        return None
    body, on = [], False
    for line in p.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("## "):
            if on:
                break
            on = line[3:].strip().lower().startswith(heading.lower())
            continue
        if on:
            body.append(line)
    text = "\n".join(body).strip()
    return text or None


def state_entries(state_dir, project):
    """Yield (relative path, first line number, heading, entry text) for every entry under <agent folder>/state/.
    Markdown entry = a list item with its continuation lines, a `|` table row, a fenced block, or a paragraph;
    a heading line sets the context and ends an entry. JSONL: one line per entry."""
    for p in sorted(list(state_dir.rglob("*.md")) + list(state_dir.rglob("*.jsonl"))):
        rel = p.relative_to(project).as_posix()
        lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
        if p.suffix == ".jsonl":
            for i, l in enumerate(lines, 1):
                if l.strip():
                    yield rel, i, "", l.strip()
            continue
        heading, cur, start, in_fence = "", [], 0, False

        def flush():
            nonlocal cur
            out = (rel, start, heading, "\n".join(cur)) if cur else None
            cur = []
            return out
        for i, l in enumerate(lines, 1):
            if in_fence:
                cur.append(l)
                if l.lstrip().startswith("```"):
                    in_fence = False
                    e = flush()
                    if e:
                        yield e
                continue
            if l.lstrip().startswith("```"):
                e = flush()
                if e:
                    yield e
                in_fence, start, cur = True, i, [l]
            elif re.match(r"#{1,6}\s", l):
                e = flush()
                if e:
                    yield e
                heading = l.lstrip("#").strip()
            elif not l.strip():
                e = flush()
                if e:
                    yield e
            elif re.match(r"\s*([-*+]|\d+[.)])\s", l) or l.lstrip().startswith("|"):
                e = flush()
                if e:
                    yield e
                start, cur = i, [l]
                if l.lstrip().startswith("|"):
                    e = flush()
                    yield e
            else:
                if not cur:
                    start = i
                cur.append(l)
        e = flush()
        if e:
            yield e


def lookup(project, keywords):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except (AttributeError, ValueError):
        pass
    state_dir = agent_dir(project) / "state"
    files = (list(state_dir.rglob("*.md")) + list(state_dir.rglob("*.jsonl"))) if state_dir.exists() else []
    kws = [k.lower() for k in keywords]
    hits = [e for e in state_entries(state_dir, project) if all(k in e[3].lower() for k in kws)] if files else []
    if not hits:
        print(f"No entries in {agent_dir(project).name}/state/ match '{' '.join(keywords)}' (searched {len(files)} files).")
        return 0
    for rel, ln, head, text in hits[:8]:
        text = text if len(text) <= 600 else text[:597] + "..."
        print(f"{rel}:{ln}" + (f" [{head}]" if head else ""))
        print(text)
        print()
    if len(hits) > 8:
        print(f"({len(hits) - 8} more entries not shown; add keywords to narrow the search)")
    return 0


def brief(project, mem):
    """Start-up summary in under 25 lines: live branch, the note's Next step, two warnings."""
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except (AttributeError, ValueError):
        pass
    print(f"Brief for {project.name} ({dt.datetime.now().strftime('%Y-%m-%d %H:%M')}); live state, trust it over the note")
    print(compact_block(project, header=False))
    nxt = resume_section(mem, "Next step")
    if nxt is None:
        print(f"Next step: no resume note or no '## Next step' section in {mem}")
    else:
        rows = nxt.splitlines()
        print("Next step: " + rows[0][:400])
        for r in rows[1:7]:
            print("  " + r[:200])
        if len(rows) > 7:
            print("  (more in the resume note)")
    sizes = [(mem / n).stat().st_size for n in ("MEMORY.md", "project_state.md") if (mem / n).exists()]
    if sum(sizes) > 4400:
        print(f"WARN: MEMORY.md plus the resume note are {sum(sizes):,} B (limit 4,400 B); move detail to {agent_dir(project).name}/state/")
    note = mem / "project_state.md"
    if note.exists():
        rc, ts = run_utf8(["git", "log", "-1", "--format=%ct"], project)
        try:
            if rc == 0 and ts and float(ts) > note.stat().st_mtime + 60:
                print("WARN: the resume note is older than the last commit; refresh its narrative and run snapshot --write-memory")
        except ValueError:
            pass
    print(f"Details: `checkpoint.py lookup <keyword>`; index at {agent_dir(project).name}/state/INDEX.md" if (agent_dir(project) / "state").exists()
          else f"No {agent_dir(project).name}/state/ folder here; details, if any, are in the memory folder")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", default=".")
    ap.add_argument("--memory-dir", default=None)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("snapshot"); s.add_argument("--write-memory", action="store_true")
    sub.add_parser("restart-check"); sub.add_parser("memory-status")
    sub.add_parser("brief")
    lk = sub.add_parser("lookup"); lk.add_argument("keywords", nargs="+")
    a = ap.parse_args()
    project, mem = paths(a.project, a.memory_dir)
    if a.cmd == "brief":
        brief(project, mem)
        return
    if a.cmd == "lookup":
        sys.exit(lookup(project, a.keywords))
    if a.cmd == "snapshot":
        text = snapshot(project, mem)
        print(text)
        if a.write_memory:
            print(f"\nupdated {write_memory(mem, compact_block(project))}")
    elif a.cmd == "restart-check":
        sys.exit(restart_check(project, mem))
    else:
        sys.exit(memory_status(project, mem))


if __name__ == "__main__":
    main()
