"""rm_tasks: the orchestrator's own task list, shown on the dashboard's Tasks tab.

Not the Phase/Feature/Story plan: a short, currently-in-mind list the orchestrator keeps and
replaces wholesale on request ("tasks set"), never auto-generated by refresh. Old lists are
archived ("tasks archive") to flat files (tasks-archive-<UTC timestamp>.json) indexed by
tasks-index.json; a tab loads one only when the viewer opens it (see tab-tasks.js / app.js's
ctx.load falling back to a literal file name for names tabs.json does not declare in `lazy`).

Commands: tasks-show, tasks-set, tasks-archive. Pure standard library.
"""
import argparse
import re
from pathlib import Path

import rm_data
from rm_data import Err, rd

TASKS_FILE = "tasks.json"
INDEX_FILE = "tasks-index.json"
ARCHIVE_PREFIX = "tasks-archive-"
STATUSES = ("pending", "active", "done")


def _empty_tasks():
    return {"schema": 1, "generated": rm_data.now_minute(), "updated": None, "title": None, "items": []}


def _empty_index():
    return {"schema": 1, "generated": rm_data.now_minute(), "archives": []}


def _read_tasks(d):
    p = d / TASKS_FILE
    return rm_data.read_json(p) if p.exists() else _empty_tasks()


def _read_index(d):
    p = d / INDEX_FILE
    return rm_data.read_json(p) if p.exists() else _empty_index()


def _write_tasks(d, tasks):
    tasks["generated"] = rm_data.now_minute()
    rm_data.write_json(d / TASKS_FILE, tasks)


def _write_index(d, index):
    index["generated"] = rm_data.now_minute()
    rm_data.write_json(d / INDEX_FILE, index)


def _parse_items(raw_items):
    items = []
    for i, it in enumerate(raw_items or []):
        if not isinstance(it, dict) or not isinstance(it.get("text"), str) or not it["text"].strip():
            raise Err(f"item {i}: needs a non-empty string 'text'")
        status = it.get("status", "pending")
        if status not in STATUSES:
            raise Err(f"item {i} ({it['text']!r}): status must be one of {', '.join(STATUSES)}, got {status!r}")
        items.append({"id": f"t{i + 1}", "text": it["text"].strip(), "status": status})
    return items


# ---------------------------------------------------------------- commands
def cmd_tasks_show(args, project):
    d = rd(project)
    tasks = _read_tasks(d)
    if not tasks["items"]:
        print("no current task list" + (f" (title: {tasks['title']})" if tasks.get("title") else ""))
        return
    if tasks.get("title"):
        print(tasks["title"])
    for it in tasks["items"]:
        print(f"  [{it['status']:>6}] {it['id']}  {it['text']}")


def cmd_tasks_set(args, project):
    d = rd(project)
    payload = rm_data.read_json(Path(args.file))
    if not isinstance(payload, dict):
        raise Err("--file must hold a JSON object with an 'items' array")
    items = _parse_items(payload.get("items"))
    title = args.title if args.title is not None else payload.get("title")
    tasks = {"schema": 1, "generated": rm_data.now_minute(), "updated": rm_data.now_minute(),
             "title": title, "items": items}
    _write_tasks(d, tasks)
    done = sum(1 for it in items if it["status"] == "done")
    rm_data.ok(f"tasks-set {len(items)} items ({done} done)", [TASKS_FILE])


def cmd_tasks_archive(args, project):
    d = rd(project)
    tasks = _read_tasks(d)
    if not tasks["items"]:
        raise Err("nothing to archive: the current task list is empty")
    stamp = rm_data.now_minute().replace(":", "").replace("Z", "Z")
    archive_id = re.sub(r"[^0-9A-Za-z]", "", stamp)
    filename = f"{ARCHIVE_PREFIX}{archive_id}.json"
    title = args.title if args.title is not None else tasks.get("title")
    archived_list = {"schema": 1, "generated": rm_data.now_minute(), "archived": rm_data.now_minute(),
                      "title": title, "items": tasks["items"]}
    rm_data.write_json(d / filename, archived_list)
    index = _read_index(d)
    index.setdefault("archives", []).insert(0, {
        "id": archive_id, "title": title, "archived": rm_data.now_minute(),
        "count": len(tasks["items"]), "done": sum(1 for it in tasks["items"] if it["status"] == "done"),
        "file": filename})
    _write_index(d, index)
    _write_tasks(d, _empty_tasks())
    rm_data.ok(f"tasks-archive {filename} ({len(tasks['items'])} items)", [filename, INDEX_FILE, TASKS_FILE])


# ---------------------------------------------------------------- registry
def register(sub):
    p = sub.add_parser("tasks-show", help="print the current task list")
    p.set_defaults(func=cmd_tasks_show)
    p = sub.add_parser("tasks-set", help="replace the current task list wholesale from a JSON file")
    p.add_argument("--file", required=True, help="JSON object: {\"title\": optional str, \"items\": "
                   "[{\"text\": str, \"status\": pending|active|done}, ...]}")
    p.add_argument("--title", help="override the file's title (or clear it if the file has none)")
    p.set_defaults(func=cmd_tasks_set)
    p = sub.add_parser("tasks-archive", help="move the current task list to the archive and clear it")
    p.add_argument("--title", help="override the archived list's title")
    p.set_defaults(func=cmd_tasks_archive)


# ---------------------------------------------------------------- selftest
def selftest():
    import contextlib
    import io
    import json
    import tempfile
    import shutil

    tmp = Path(tempfile.mkdtemp(prefix="rm_tasks_selftest_"))
    try:
        proj = tmp / "proj"
        d = rd(proj)
        d.mkdir(parents=True)

        ap = argparse.ArgumentParser()
        sub = ap.add_subparsers(dest="cmd", required=True)
        register(sub)

        def run(*argv, fail=False):
            buf = io.StringIO()
            try:
                a = ap.parse_args(list(argv))
                with contextlib.redirect_stdout(buf):
                    a.func(a, proj)
            except Err as e:
                if not fail:
                    raise AssertionError(f"{argv} failed: {e}")
                return str(e)
            if fail:
                raise AssertionError(f"{argv} should have failed")
            return buf.getvalue()

        def check(c, msg):
            if not c:
                raise AssertionError(msg)

        check("no current task list" in run("tasks-show"), "show on empty project")

        items_file = tmp / "items.json"
        items_file.write_text(json.dumps({"title": "Session A", "items": [
            {"text": "Do the thing"}, {"text": "Do another thing", "status": "done"}]}), encoding="utf-8")
        out = run("tasks-set", "--file", str(items_file))
        check(out.startswith("ok tasks-set 2 items (1 done)"), f"set output: {out}")
        tasks = json.loads((d / TASKS_FILE).read_text())
        check(tasks["title"] == "Session A" and tasks["items"][0]["id"] == "t1"
              and tasks["items"][0]["status"] == "pending" and tasks["items"][1]["status"] == "done",
              "set content")

        bad = tmp / "bad.json"
        bad.write_text(json.dumps({"items": [{"text": "x", "status": "nope"}]}), encoding="utf-8")
        check("status must be one of" in run("tasks-set", "--file", str(bad), fail=True), "bad status refused")

        show_out = run("tasks-show")
        check("Session A" in show_out and "t1" in show_out, "show content")

        out = run("tasks-archive")
        check(out.startswith("ok tasks-archive tasks-archive-"), f"archive output: {out}")
        index = json.loads((d / INDEX_FILE).read_text())
        check(len(index["archives"]) == 1 and index["archives"][0]["title"] == "Session A"
              and index["archives"][0]["count"] == 2 and index["archives"][0]["done"] == 1, "index content")
        archived_file = d / index["archives"][0]["file"]
        check(archived_file.exists(), "archive file written")
        archived = json.loads(archived_file.read_text())
        check(len(archived["items"]) == 2 and archived["items"][0]["id"] == "t1", "archived file content")
        check("no current task list" in run("tasks-show"), "current list cleared after archive")

        check("nothing to archive" in run("tasks-archive", fail=True), "archiving an empty list refused")

        items_file.write_text(json.dumps({"items": [{"text": "B"}]}), encoding="utf-8")
        run("tasks-set", "--file", str(items_file))
        out = run("tasks-archive", "--title", "Session B (renamed)")
        index = json.loads((d / INDEX_FILE).read_text())
        check(index["archives"][0]["title"] == "Session B (renamed)" and len(index["archives"]) == 2,
              "second archive prepended with title override")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
